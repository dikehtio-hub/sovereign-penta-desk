def write_views(vault: Path, *, force: bool = False, dry_run: bool = False) -> tuple[list[str], list[str]]:
    written: list[str] = []
    skipped: list[str] = []
    targets: list[tuple[Path, str]] = [(vault / VIEWS_DIR / f"{v.name}.base", base_yaml(v)) for v in VIEWS]
    targets += [(vault / TEMPLATES_DIR / f"{k}.md", body) for k, body in TEMPLATES.items()]
    for path, text in targets:
        assert_owned(path, vault)
        rel = path.relative_to(vault).as_posix()
        if path.exists() and not force:
            skipped.append(rel)
            continue
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        written.append(rel)
    return written, skipped


def main(argv: list[str] | None = None, out=None) -> int:
    out = out or sys.stdout
    ap = argparse.ArgumentParser(prog="knowledge.views", description=__doc__.split("\n\n")[0])
    ap.add_argument("--vault", type=Path, default=VAULT)
    ap.add_argument("--dev-root", type=Path, default=DEV_ROOT)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    if halted(args.dev_root):
        print(f"[HALT] {args.dev_root / 'HALT.flag'} present - views refuses (exit {EXIT_HALT})", file=out)
        return EXIT_HALT
    if not args.vault.is_dir():
        print(f"[REFUSE] vault not found: {args.vault} (exit {EXIT_HALT})", file=out)
        return EXIT_HALT
    written, skipped = write_views(args.vault, force=args.force, dry_run=args.dry_run)
    for r in written:
        print(("[DRY]   " if args.dry_run else "[WRITE] ") + r, file=out)
    for r in skipped:
        print("[KEEP]  " + r, file=out)
    print(f"views: {len(written)} written, {len(skipped)} kept ({len(VIEWS)} .base views, {len(TEMPLATES)} templates)", file=out)
    return EXIT_OK


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
