"""Obsidian Bases views and page templates (Round 101, B13).

    python -m knowledge.views [--force] [--dry-run]

Writes wiki/_views/<name>.base (Obsidian 1.9+ Bases: YAML with `filters` and `views`)
for the compiled types, and wiki/_templates/<kind>.md scaffolds whose frontmatter
already satisfies OKF v0.2 (`type`, `generated.by: human:operator`, ...), so a page a
human creates from a template passes lint L1 the moment it is saved. Folders whose
name starts with `_` are tooling, not pages: lint and the index skip them.

Bases filters use `file.inFolder(...)`, which matches the folder-per-type layout of
WIKI_SCHEMA.md s.4 and needs no property that a nested `dev:` mapping would hide.
Settings the operator should make in Obsidian (never written by this package):
Templates -> template folder `wiki/_templates`; Daily notes -> folder `journal`.
"""
